public class pushupBasics {
    public static void main(String args[]) {

        int pushup;

        int set = 3;

        for (int rep = 1; rep <= set; rep++) {
            System.out.println("Set :" + rep);
            for (pushup = 1; pushup <= 10; pushup++) {
                System.out.println("pushup :" + pushup);
            }
        }

    }
}
